"""Display/audit generated controls without changing stored token IDs."""
import unicodedata

def generation_integrity(ids, tok):
    unexpected = {tok.pad, tok.unk, tok.bos, tok.system, tok.user, tok.assistant}
    bad = [dict(position=n, id=int(i), piece=tok.sp.id_to_piece(int(i))) for n, i in enumerate(ids) if i in unexpected]
    decoded = tok.decode(ids, visible_controls=True)
    nonprinting = [dict(position=i, codepoint=f'U+{ord(ch):04X}', category=unicodedata.category(ch)) for i, ch in enumerate(decoded) if unicodedata.category(ch) in ('Cc', 'Cs') and ch not in '\n\r\t']
    replacements = decoded.count('�')
    return dict(format_valid=not bad and (not nonprinting) and (not replacements), unexpected_controls=bad, decoded_nonprinting_controls=nonprinting, decoded_replacement_characters=replacements, format_audit_version=2, decode_preserves_control_tokens=True)

def escape_controls(text):
    """Display every generated byte control explicitly; never change the stored token/history IDs."""
    return ''.join((f'\\u{ord(ch):04x}' if unicodedata.category(ch) in ('Cc', 'Cs') and ch not in '\n\r\t' else ch for ch in text))
