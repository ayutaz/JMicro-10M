def main():
    raw=RUN/f'evaluation/{ARM}/evaluation/generation.json'; destination=RUN/'content-notes.json'
    if destination.exists():raise ValueError('Preserve actual individual midpoint notes')
    rows=read_json(raw)['outputs']
    if [r['id'] for r in rows]!=[n[0] for n in OBSERVATIONS]:
        raise ValueError('Every original80 observation required in actual order')
    oldraw=ROOT/'reports/phase6/source-order-condition-comparison-v2-20261006/evaluation/source_order/evaluation/generation.json'
    oldnotes=ROOT/'reports/phase6/source_order_condition_notes.json'
    originals={r['id']:r for r in read_json(oldraw)['outputs']}; old={n[0]:n for n in read_json(oldnotes)['notes']}
    notes=[]; reused=[]; per_text=[]
    for row,note in zip(rows,OBSERVATIONS,strict=True):
        before=originals[row['id']]
        if all(row[k]==before[k] for k in ('prefix','generated_ids','text','stop_reason')):
            if list(note[1:5])!=old[row['id']][1:5]:
                raise ValueError('Identical original continuation must keep existing scores')
            notes.append(old[row['id']]);reused.append(row['id'])
        else:notes.append(list(note))
        per_text.append(dict(id=row['id'],text_sha256=hashlib.sha256(row['text'].encode('utf-8')).hexdigest()))
    atomic_json(destination,dict(created_at=now(),generation_sha256=sha256(raw),reviewer='Codex nonblind; all80 individually read',
        independent_human_blind=False,all80_individually_read=True,notes=notes,text_references=per_text,
        exact_old_score_reuse=dict(ids=reused,raw=dict(path=str(oldraw),sha256=sha256(oldraw)),
            notes=dict(path=str(oldnotes),sha256=sha256(oldnotes))),
        rubric='Grammar/relevance/coherence0-2, appropriate completion0-1. Numerical correctness separate from syntax. '
            'Implicit new people, reasonable alternative actions, fictional equipment and absent gold agreement are not automatic errors. '
            'No changed decoder, re-rating to satisfy aggregate gates or human-blind claim.'))
    print(dict(notes=80,exact_old_score_reuse=len(reused)))


if __name__=='__main__':main()
