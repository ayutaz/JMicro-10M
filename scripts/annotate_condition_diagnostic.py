def parse(text):
    rows=[]
    for line in text.strip().splitlines():
        fields=line.split('|',5)
        rows.append(['base-'+fields[0],*[int(x) for x in fields[1:5]],fields[5]])
    return rows


def main():
    arms={}
    for arm,text in [('compact',COMPACT),('expanded',EXPANDED)]:
        notes=parse(text)
        assert len(notes)==80 and len({n[0] for n in notes})==80
        p=study.RUN/'evaluation'/arm/'evaluation/generation.json'
        raw=read_json(p)['outputs'];assert {r['id'] for r in raw}=={n[0] for n in notes}
        arms[arm]=dict(generation_sha256=sha256(p),notes=notes,
                      raw_by_id={r['id']:dict(prefix=r['prefix'],text=r['text'],stop_reason=r['stop_reason'],generated_ids=r['generated_ids']) for r in raw})
    write_json(study.RUN/'annotations.json',dict(arms=arms,reviewer='Codex nonblind after all raw outputs read',
        independent_human_blind=False,annotator_sha256=sha256(Path(__file__)),created_at=now()))
    print('Saved all160 individual raw-bound judgments')


if __name__=='__main__':main()
