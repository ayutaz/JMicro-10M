def main():
    path = DATA / 'content-notes.json'
    if path.exists(): raise ValueError('Preserve actual individual notes; no post-pilot revision')
    pilot = read_json(DATA / 'content-pilot.json')
    if len(REASONS) != 64 or len(pilot['rows']) != 64: raise ValueError('All64 observations required')
    weak = {3, 18, 34, 43, 50, 51, 63}; grammar = {43, 51, 63}; grounding = {63}
    notes = []
    for index, row in enumerate(pilot['rows']):
        notes.append(dict(id=row['id'], text_sha256=row['text_sha256'], paired_condition_outcome=1 if index in weak else 2,
            weak_document=index in weak, unresolved_grammar_issue=index in grammar,
            unresolved_grounding_issue=index in grounding, reason=REASONS[index]))
    raw = dict(status='all64_actual_individual_nonblind_content_observations', created_at=now(),
        pilot_sha256=sha256(DATA / 'content-pilot.json'), all64_individually_read=True, notes=notes,
        reviewer='Codex nonblind', independent_human_blind=False,
        semantics='Grammar flags denote unresolved natural grammatical expression, not a formal proof that every marked sentence has no possible syntactic parse.',
        no_renderer_or_pilot_corrections_after_actual_preparation=True,
        protected_test_used=False, actual_GPU_seconds=0, scientific_teacher_tokens=0)
    atomic_json(path, raw); atomic_json(RUN / 'content-notes.json', raw)
    print(dict(read=64, weak=7, unresolved_grammar=3, unresolved_grounding=1))


if __name__ == '__main__':
    if sys.version_info[:3] != (3, 12, 7): raise RuntimeError('Pinned uv Python3.12.7 required')
    main()
