def main():
    raw=study.RUN/f'evaluation/{study.ARM}/evaluation/generation.json'
    rows=read_json(raw)['outputs'];old=old_exact_scores()
    for source,notes in [
        ('reports/phase6/historical-parent-condition-comparison-v3-20261006/evaluation/historical_parent/evaluation/generation.json','reports/phase6/historical_parent_condition_notes.json'),
        ('reports/phase6/conditional-prefix-mask-20261006/evaluation/outcome_EOS_only/evaluation/generation.json','reports/phase6/conditional-prefix-mask-20261006/content-notes.json'),
        ('reports/phase6/parameter-displacement-anchor-v3-20261006/evaluation/parameter_anchor/evaluation/generation.json','reports/phase6/parameter-displacement-anchor-v3-20261006/parameter_anchor-content-notes.json')]:
        p=ROOT/source;previous=read_json(p)['outputs'];scores=validate_notes(previous,read_json(ROOT/notes),sha256(p))
        for row in previous:old.setdefault(signature(row),(scores[row['id']],source))
    supplied={'base-'+v[0]:v for v in OBSERVATIONS}
    if len(rows)!=80 or len(supplied)!=80 or set(supplied)!={r['id'] for r in rows}:raise ValueError('All80 read observations required')
    destination=study.RUN/'content-notes.json'
    if destination.exists():raise ValueError('Preserve original all80 notes')
    notes=[];reuse=[]
    for row in rows:
        key=signature(row)
        if key in old:
            score,source=old[key];g,r,c,done=[score[k] for k in ('grammar','relevance','coherence','completion')]
            rationale='元raw全項目一致で旧採点をそのまま継承：'+score['rationale'];reuse.append(dict(id=row['id'],source=source))
        else:g,r,c,done,rationale=supplied[row['id']][1:]
        notes.append([row['id'],g,r,c,done,rationale])
    record=dict(reviewer='Codex nonblind; all80 individually read',independent_human_blind=False,created_at=now(),generation_sha256=sha256(raw),
        notes=notes,all80_individually_read=True,exact_old_score_reuse=reuse,
        raw_row_sha256={r['id']:hashlib.sha256(signature(r).encode()).hexdigest() for r in rows},
        rubric='Grammar/relevance/local consistency/complete EOS ending scored separately. Fantasy/new people/implicit equipment/natural alternative actions/absence of gold text are not automatic failures. Arithmetic errors are not grammar errors. Nonblind Codex; no independent human review.')
    validate_notes(rows,record,sha256(raw));atomic_json(destination,record)
    print(json.dumps(dict(individually_read=80,exact_previous_scores_reused=len(reuse))))


if __name__=='__main__':main()
