def signature(row):
    keys=('id','prefix','generated_ids','text','valid_utf8','role_leak','empty_response','stop_reason','repetition')
    return json.dumps({k:row[k] for k in keys},ensure_ascii=False,sort_keys=True)


def old_exact_scores():
    old={}
    for raw,notes in [
        ('reports/phase6/source-order-condition-comparison-v2-20261006/evaluation/source_order/evaluation/generation.json','reports/phase6/source_order_condition_notes.json'),
        ('reports/phase6/weight-average-comparison-20261006/evaluation/midpoint50/evaluation/generation.json','reports/phase6/weight-average-comparison-20261006/content-notes.json'),
        ('reports/phase6/parameter-displacement-anchor-v3-20261006/evaluation/matched_staged_CE/evaluation/generation.json',
         'reports/phase6/parameter-displacement-anchor-v3-20261006/matched_staged_CE-content-notes.json')]:
        path=ROOT/raw
        if not path.exists() or not (ROOT/notes).exists():continue
        rows=read_json(path)['outputs'];scores=validate_notes(rows,read_json(ROOT/notes),sha256(path))
        for row in rows:old.setdefault(signature(row),(scores[row['id']],raw))
    return old


def write(arm,observations,inspect_only=False):
    raw=study.RUN/f'evaluation/{arm}/evaluation/generation.json';rows=read_json(raw)['outputs'];old=old_exact_scores()
    if inspect_only:
        print([(r['id'],old[signature(r)][0]) for r in rows if signature(r) in old]);return
    destination=study.RUN/f'{arm}-content-notes.json'
    if destination.exists():raise ValueError('Preserve original all80 notes')
    supplied={'base-'+row[0]:row for row in observations}
    if len(rows)!=80 or set(supplied)!={r['id'] for r in rows}:raise ValueError('All80 individually read observations required')
    notes=[];reuse=[]
    for row in rows:
        key=signature(row);value=supplied[row['id']]
        if key in old:
            score,source=old[key];g,r,c,done=[score[k] for k in ('grammar','relevance','coherence','completion')]
            rationale='元raw全項目が一致し旧採点をそのまま継承：'+score['rationale'];reuse.append(dict(id=row['id'],source=source))
        else:g,r,c,done,rationale=value[1:]
        notes.append([row['id'],g,r,c,done,rationale])
    record=dict(reviewer='Codex nonblind; all80 individually read',independent_human_blind=False,created_at=now(),
        generation_sha256=sha256(raw),notes=notes,all80_individually_read=True,exact_old_score_reuse=reuse,
        raw_row_sha256={r['id']:hashlib.sha256(signature(r).encode()).hexdigest() for r in rows},
        rubric='Judge grammar, relevance, local consistency and a complete EOS ending separately. '
            'Fantasy/new people/implicit equipment/natural alternative actions/absence of gold text are not automatic failures. '
            'Arithmetic errors do not themselves imply broken grammar. No independent human or factual certification.')
    validate_notes(rows,record,sha256(raw));atomic_json(destination,record)
    print(dict(arm=arm,individually_read=len(notes),exact_previous_scores_reused=len(reuse)))


