WEAK = {4, 5, 9, 16, 29, 35, 36, 44, 45, 49, 60, 61}
GRAMMAR = {4, 9, 29, 36, 44, 45}
GROUNDING = {16, 35}


def main():
    destination = RUN / 'content-notes.json'
    if destination.exists():
        raise ValueError('Preserve actual individual notes; do not rerate frozen pilot')
    pilot = read_json(RUN / 'content-pilot.json')
    if len(REASONS) != 64 or [r['index'] for r in pilot['rows']] != list(range(64)):
        raise ValueError('Every original fixed64 row is required')
    notes = [dict(id=r['id'], text_sha256=r['text_sha256'],
                  content_quality=1 if i in WEAK else 2, weak_document=i in WEAK,
                  unresolved_grammar_issue=i in GRAMMAR,
                  unresolved_grounding_issue=i in GROUNDING, reason=REASONS[i])
             for i, r in enumerate(pilot['rows'])]
    atomic_json(destination, dict(created_at=now(), pilot_sha256=sha256(RUN / 'content-pilot.json'),
        all64_individually_read=True, reviewer='Codex nonblind', independent_human_blind=False,
        external_fact_certification=False, notes=notes,
        rubric='Whole Japanese readability and internal coherence. Fantasies, tragic endings, implicit actions and unused initial traits are not automatic errors. Flags concern unresolved expressions or subject/object chronology; no source/pilot corrections.'))
    print(dict(notes=len(notes), weak=len(WEAK), grammar=len(GRAMMAR), grounding=len(GROUNDING)))


if __name__ == '__main__':
    main()
