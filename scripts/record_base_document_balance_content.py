def main():
    raw=RUN/'evaluation/document_balance/evaluation/generation.json'
    data=json.loads(raw.read_text())
    assert len(data['outputs'])==len(SCORES)==80
    assert all(row['split']=='dev' for row in data['outputs'])
    scores=[['base-'+key,g,r,c,a,reason] for key,g,r,c,a,reason in SCORES]
    assert {row[0] for row in scores}=={row['id'] for row in data['outputs']}
    old=json.loads(NOTES.read_text())
    assert all(row[1] is None for row in old['notes']), 'Do not overwrite prior content judgments'
    template=ROOT/'reports/phase6/base_document_balance_notes_unscored_template.json'
    if template.exists(): raise ValueError('Preserve original template')
    shutil.copyfile(NOTES,template)
    notes=dict(reviewer='Codex nonblind; every original80 prefix and entire raw continuation individually read',
        independent_human_blind=False,all80_individually_read=True,
        generation_sha256=hashlib.sha256(raw.read_bytes()).hexdigest(),notes=scores,
        limitation='Repeated fixed DEV, one trained seed, no independent human blind. Semantic repetition is described in reasons without changing raw automatic flags. No TEST cases read by this recorder.')
    NOTES.write_text(json.dumps(notes,indent=2,ensure_ascii=False)+'\n')
    print(json.dumps(dict(individually_read=80,grammar2=sum(row[1]==2 for row in scores),
        relevance2=sum(row[2]==2 for row in scores),coherence2=sum(row[3]==2 for row in scores),
        appropriate=sum(row[4] for row in scores),generation_sha256=notes['generation_sha256'])))


if __name__=='__main__':
    if sys.version_info[:3]!=(3,12,7): raise RuntimeError('Pinned uv Python3.12.7 required')
    main()
