    raw=study.RUN/f'evaluation/{study.ARM}/evaluation/generation.json';rows=read_json(raw)['outputs'];old=old_exact_scores()
    # Preserve the already completed L2 arm too when every bound raw item agrees.
    source='reports/phase6/parameter-displacement-anchor-v3-20261006/evaluation/parameter_anchor/evaluation/generation.json'
    old_raw=ROOT/source;old_notes=ROOT/'reports/phase6/parameter-displacement-anchor-v3-20261006/parameter_anchor-content-notes.json'
    prior_rows=read_json(old_raw)['outputs'];prior_scores=validate_notes(prior_rows,read_json(old_notes),sha256(old_raw))
    for row in prior_rows:old.setdefault(signature(row),(prior_scores[row['id']],source))
